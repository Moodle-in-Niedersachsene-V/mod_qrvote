/**
 * Keeps one random voter key per browser so a device is counted once per round.
 *
 * The key is random and contains no personal data. The server stores only a hash of it
 * keyed with the round secret. If the browser blocks storage, the key generated by the
 * server for this page is used.
 *
 * @module     mod_qrvote/voterkey
 * @copyright  2026 Moodle in Niedersachsen e. V.
 * @license    https://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */

/** @type {string} Storage key. */
const STORAGEKEY = 'mod_qrvote_voterkey';

/** @type {RegExp} Format of a voter key. */
const PATTERN = /^[a-f0-9]{32}$/;

/**
 * Puts the stored voter key into the ballot, or stores the key the server generated.
 */
export const init = () => {
    const field = document.querySelector('form input[name="voterkey"]');
    if (!field) {
        return;
    }
    try {
        const stored = window.localStorage.getItem(STORAGEKEY);
        if (stored && PATTERN.test(stored)) {
            field.value = stored;
        } else if (PATTERN.test(field.value)) {
            window.localStorage.setItem(STORAGEKEY, field.value);
        }
    } catch {
        // Storage is blocked, for example in a private window; the key of this page is used.
    }
};
